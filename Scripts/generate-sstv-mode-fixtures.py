"""Development only: PYTHONPATH pointing to dnet/pySSTV 0.5.9 sources + Pillow.
Generate our own changing color bars through an independent encoder's public API.
No third-party implementation is shipped in AnaLine.
"""
import json
from pathlib import Path
from PIL import Image
from pysstv.color import MartinM1, ScottieS1, PD120

colors = [(255,255,255),(255,255,0),(0,255,255),(0,255,0),(255,0,255),(255,0,0),(0,0,255),(0,0,0)]
root = Path(__file__).resolve().parent.parent
for name, mode in [('martin-m1',MartinM1),('scottie-s1',ScottieS1),('pd120',PD120)]:
    image = Image.new('RGB',(mode.WIDTH,mode.HEIGHT))
    image.putdata([colors[(x//(mode.WIDTH//8)+y//32)%8] for y in range(mode.HEIGHT) for x in range(mode.WIDTH)])
    runs = []
    for hz, ms in mode(image,12000,16).gen_freq_bits():
        seconds = ms/1000
        if runs and runs[-1][0] == hz:
            runs[-1][1] += seconds
        else:
            runs.append([hz,seconds])
    path = root/'Tests'/'Fixtures'/f'{name}-pysstv-bars.json'
    path.write_text(json.dumps({'source':'dnet/pySSTV 0.5.9 API; own rotating RGB bars; Pillow YCbCr; generated by Scripts/generate-sstv-mode-fixtures.py','runs':runs},separators=(',',':'))+'\n')
    print(name, len(runs), sum(r[1] for r in runs))
